# QS01 · 认识 PyMotion Lite
#
# PyMotion Lite 是用于学习运动控制和连接传感器、执行器的控制板。
# Python 程序可以通过它控制直流电机和舵机、读取传感器与雷达数据，
# 并在 OLED 上显示文字或设备信息。
#
# 快速入门会沿着下面的路线认识和使用 Lite：
#
# 1. 连接 Lite，读取设备标识和状态；
# 2. 读取 M1 电机状态，并让空载电机短时间低速运行；
# 3. 在反馈有效时演示归零、绝对位置和相对位置运动；
# 4. 读取超声波距离，并把结果显示在 OLED 上。
#
# 板卡上的主要功能区域包括：
#
# - USB：连接电脑与 Lite；
# - 电源：为板卡及外设提供符合产品要求的供电；
# - M1～M4：连接直流电机；
# - 舵机接口：连接受支持的 PWM 或 TTL 总线舵机；
# - 传感器与雷达接口：获取距离、姿态、光线、颜色等环境信息；
# - OLED：显示文字和设备信息。
#
# 本文件只有文字注释，不需要运行，也不会连接或控制任何硬件。
# 请先对照与实际硬件版本一致的正式说明书辨认接口，不要根据接口外形
# 猜测电压、极性或插头方向。完成阅读后，从 02-connection.py 开始运行代码。
